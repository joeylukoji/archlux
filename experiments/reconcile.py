"""Reconcile the paper's numbers (B1-B9) with the raw rows of results/.

Usage: python experiments/reconcile.py [RESULTS_DIR]. Writes RECONCILIATION.md and
reconciliation.json next to the raw files. See archlux.bench.reconcile.
"""

import json
import sys
from pathlib import Path

from archlux.bench.reconcile import reconcile, to_json, to_markdown

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
claims = reconcile(ROOT)
HEADER = """# Reconciliation of the paper's numbers with the raw results

Generated by `python experiments/reconcile.py` from the files of this directory: do not
edit by hand. Verdicts: **consistent** (the raw rows give the printed number),
**article_wrong** (they give another one, or the denominator is wrong), **ambiguous**
(right number, misleading wording or unit), **cannot_verify** (no raw row published).
Cluster-bootstrap intervals resample the statistical unit (plan, dwelling), seed 17.

"""
(ROOT / "RECONCILIATION.md").write_text(HEADER + to_markdown(claims), encoding="utf-8")
(ROOT / "reconciliation.json").write_text(
    json.dumps(to_json(claims), indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
)
